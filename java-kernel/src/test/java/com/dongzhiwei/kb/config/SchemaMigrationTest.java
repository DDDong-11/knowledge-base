package com.dongzhiwei.kb.config;

import com.dongzhiwei.kb.domain.SnippetKind;
import com.dongzhiwei.kb.domain.SnippetSource;
import com.dongzhiwei.kb.dto.SnippetResponse;
import com.dongzhiwei.kb.repository.SnippetRepository;
import com.dongzhiwei.kb.service.SnippetService;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.core.io.ClassPathResource;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.init.ScriptUtils;
import org.springframework.test.context.ActiveProfiles;
import org.springframework.test.context.DynamicPropertyRegistry;
import org.springframework.test.context.DynamicPropertySource;

import javax.sql.DataSource;
import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.Statement;

import static org.assertj.core.api.Assertions.assertThat;

/**
 * 第 1-4 步建出的旧库（无 kind/source 列）在第 5 步内核启动时被 schema.sql 幂等补列，
 * 且 Hibernate ddl-auto=validate 能通过。
 */
@SpringBootTest
@ActiveProfiles("test")
class SchemaMigrationTest {

    private static final String URL = "jdbc:h2:mem:kbmigr;DB_CLOSE_DELAY=-1";

    @DynamicPropertySource
    static void legacyDatabase(DynamicPropertyRegistry registry) throws Exception {
        try (Connection c = DriverManager.getConnection(URL, "sa", "");
             Statement st = c.createStatement()) {
            // 第 1-4 步的 schema.sql 原样
            st.execute("""
                    CREATE TABLE IF NOT EXISTS snippet (
                        id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        title       VARCHAR(200)  NOT NULL,
                        content     CHARACTER LARGE OBJECT,
                        tags        VARCHAR(1000),
                        create_time TIMESTAMP(6)  NOT NULL,
                        update_time TIMESTAMP(6)  NOT NULL
                    )""");
            st.execute("CREATE INDEX IF NOT EXISTS idx_snippet_update_time ON snippet (update_time)");
            st.execute("INSERT INTO snippet (title, content, tags, create_time, update_time) "
                    + "VALUES ('legacy', 'old row', 'a', CURRENT_TIMESTAMP, CURRENT_TIMESTAMP)");
        }
        registry.add("spring.datasource.url", () -> URL);
    }

    @Autowired SnippetRepository repository;
    @Autowired SnippetService service;
    @Autowired JdbcTemplate jdbc;
    @Autowired DataSource dataSource;

    @Test
    void legacyRowsGetDefaultKindAndSource() {
        Long id = jdbc.queryForObject("SELECT id FROM snippet WHERE title = 'legacy'", Long.class);
        SnippetResponse legacy = service.get(id);
        assertThat(legacy.kind()).isEqualTo(SnippetKind.NOTE);
        assertThat(legacy.source()).isEqualTo(SnippetSource.MANUAL);
        assertThat(legacy.content()).isEqualTo("old row");
    }

    @Test
    void kindIndexExistsAndSchemaScriptIsIdempotent() throws Exception {
        Integer idx = jdbc.queryForObject(
                "SELECT COUNT(*) FROM INFORMATION_SCHEMA.INDEXES WHERE INDEX_NAME = 'IDX_SNIPPET_KIND'", Integer.class);
        assertThat(idx).isEqualTo(1);
        try (Connection c = dataSource.getConnection()) {
            ScriptUtils.executeSqlScript(c, new ClassPathResource("schema.sql"));
            ScriptUtils.executeSqlScript(c, new ClassPathResource("schema.sql"));
        }
        assertThat(repository.count()).isGreaterThanOrEqualTo(1);
    }
}
